/**
 * Clearly labelled Mock Prototype Service Layer.
 * Executed ONLY when no live AI key or external FastAPI ML backend is configured,
 * ensuring the Next.js UI remains 100% interactive with honest, non-fabricated outputs.
 */

export function buildMockImageInvestigation(input: {
  fileName: string;
  fileSize: string;
  dimensions: string;
  mimeType: string;
  aspectRatio: string;
  exifStatus: string;
  lastModified?: string;
  userContext?: string;
}): InvestigationRecord {
  const id = generateInvestigationId("VR");
  const nowIso = new Date().toISOString();

  const hasExif = input.exifStatus.toLowerCase().includes("present");

  const imageResult: ImageAnalysisResult = {
    overallAssessment: "Mixed / Inconclusive Signals",
    possibleManipulationIndicators: [
      {
        area: "Container & Metadata Header",
        observation: `Client-side binary scan reported: ${input.exifStatus}.`,
        severity: hasExif ? "low" : "moderate",
      },
      {
        area: "Deep Pixel Forensics (Pending Backend)",
        observation:
          "Frequency-domain ELA and neural manipulation scoring await connection to the Python FastAPI PyTorch/OpenCV pipeline or live Gemini API key.",
        severity: "low",
      },
    ],
    metadataInfo: {
      fileName: input.fileName,
      fileSize: input.fileSize,
      dimensions: input.dimensions,
      mimeType: input.mimeType,
      aspectRatio: input.aspectRatio,
      exifStatus: input.exifStatus,
      lastModified: input.lastModified,
    },
    visualConsistencyFindings: [
      {
        check: "Resolution & Aspect Geometry",
        finding: `Image decoded cleanly at ${input.dimensions} (${input.aspectRatio} aspect ratio, ${input.fileSize}).`,
        status: "consistent",
      },
      {
        check: "Shadow & Illumination Forensics",
        finding:
          "Mock prototype mode cannot evaluate pixel-level lighting vectors; connect FastAPI CV service or GEMINI_API_KEY for live visual inspection.",
        status: "inconclusive",
      },
    ],
    aiGeneratedIndicators: [
      {
        signal: "Generative Artifact Screening",
        observation:
          "Not evaluated by a live vision model in mock prototype mode.",
        likelihoodNote:
          "Inconclusive without live model inference or C2PA provenance.",
      },
    ],
    confidenceRange: {
      low: 42,
      high: 58,
      label: "42%–58% (Mock Prototype — Pending Backend)",
    },
    uncertaintySummary:
      "Mock prototype output based solely on client container metadata. No live ML or vision model scored pixel manipulation.",
    explanation: `Inspected '${input.fileName}' (${input.dimensions}, ${input.fileSize}). ${input.exifStatus}.${
      input.userContext ? ` Submitted context noted: "${input.userContext}".` : ""
    } Because neither a Python FastAPI vision pipeline nor GEMINI_API_KEY is connected in this environment, this result is generated by the clearly labelled mock service layer without claiming authenticity or manipulation.`,
    limitations: [
      "Mock Prototype Layer: No live PyTorch, OpenCV, or Gemini vision model was invoked.",
      "No single model prediction can certify an image as definitely real or fake.",
      "Configure GEMINI_API_KEY or connect the FastAPI backend for live pixel-level forensics.",
    ],
  };

  return {
    id,
    type: "image",
    title: input.fileName || "Submitted Image Inspection",
    submittedSummary: `Submitted ${input.fileName} (${input.dimensions}, ${input.fileSize}) for authenticity screening.`,
    createdAt: nowIso,
    status: "completed",
    assessmentLabel: imageResult.overallAssessment,
    assessmentCategory: "neutral",
    confidenceLabel: imageResult.confidenceRange.label,
    dataOrigin: "Sample Baseline (Mock)",
    imageResult,
    evidenceTable: [
      {
        factor: "File Dimensions & Container",
        observation: `${input.dimensions} · ${input.mimeType} · ${input.fileSize}`,
        signal: "Verified Locally",
        weight: "Metadata",
      },
      {
        factor: "EXIF Header Check",
        observation: input.exifStatus,
        signal: hasExif ? "Present" : "Absent / Stripped",
        weight: "Contextual",
      },
      {
        factor: "Neural Pixel Forensics",
        observation: "Awaiting FastAPI CV backend or GEMINI_API_KEY",
        signal: "Inconclusive",
        weight: "Pending",
      },
    ],
    modelFindings: [
      {
        module: "Mock Prototype Adapter (FastAPI Placeholder)",
        summary: imageResult.explanation,
        uncertainty: "Live model inference not connected",
      },
    ],
    sources: [],
    limitations: imageResult.limitations,
  };
}

export function buildMockNewsInvestigation(input: {
  url?: string;
  claimText?: string;
  type?: "news" | "text";
}): InvestigationRecord {
  const id = generateInvestigationId("VR");
  const nowIso = new Date().toISOString();
  const rawClaim =
    input.claimText?.trim() ||
    (input.url ? `Article submitted for verification: ${input.url}` : "Submitted statement");

  const sentences = rawClaim
    .split(/(?<=[.!?])\s+/)
    .map((s) => s.trim())
    .filter(Boolean)
    .slice(0, 3);

  const extractedClaims = (sentences.length > 0 ? sentences : [rawClaim]).map(
    (s, idx) => ({
      id: `CLM-${idx + 1}`,
      claim: s,
      assessment: "Unverified" as const,
      rationale:
        "Mock prototype mode does not perform live web retrieval or fabricate citations; marked Unverified until connected to FastAPI retrieval or GEMINI_API_KEY.",
    })
  );

  const newsResult: NewsAnalysisResult = {
    originalClaim: rawClaim,
    sourceUrl: input.url || undefined,
    assessment: "Unverified",
    extractedClaims,
    supportingEvidence: [],
    contradictingEvidence: [],
    sources: input.url
      ? [
          {
            name: (() => {
              try {
                return new URL(input.url).hostname.replace(/^www\./, "");
              } catch {
                return "Submitted URL";
              }
            })(),
            title: "User-Submitted Reference URL (Unfetched in Mock Mode)",
            url: input.url,
            publishedDate: "Submitted by user",
          },
        ]
      : [],
    analysisTimestamp: nowIso,
    confidenceRange: {
      low: 35,
      high: 52,
      label: "35%–52% (Mock Prototype — Unverified)",
    },
    explanation:
      "Your submission was parsed and decomposed into atomic claim candidates by the mock prototype service layer. Because live evidence retrieval (FastAPI NLP/RAG or GEMINI_API_KEY) is not connected, VerityAI refuses to fabricate verification verdicts or citations and honestly classifies the claim as Unverified.",
    limitations: [
      "Mock Prototype Layer: Live search grounding and external source retrieval are not connected.",
      "VerityAI never fabricates news articles, quotes, or publication dates in mock mode.",
      "Configure GEMINI_API_KEY or attach the FastAPI retrieval backend for live fact-checking.",
    ],
  };

  return {
    id,
    type: input.type || (input.url ? "news" : "text"),
    title:
      rawClaim.length > 64 ? `${rawClaim.slice(0, 61)}...` : rawClaim,
    submittedSummary: rawClaim,
    createdAt: nowIso,
    status: "completed",
    assessmentLabel: "Unverified",
    assessmentCategory: "neutral",
    confidenceLabel: newsResult.confidenceRange.label,
    dataOrigin: "Sample Baseline (Mock)",
    newsResult,
    evidenceTable: extractedClaims.map((c) => ({
      factor: c.id,
      observation: `${c.claim} — ${c.rationale}`,
      signal: "Unverified",
      weight: "Claim Parsed",
    })),
    modelFindings: [
      {
        module: "Mock Claim Decomposition Adapter (FastAPI Placeholder)",
        summary: newsResult.explanation,
        uncertainty: "Live web corroboration unavailable in mock mode",
      },
    ],
    sources: newsResult.sources,
    limitations: newsResult.limitations,
  };
}

export function buildMockDocumentInvestigation(input: {
  fileName: string;
  fileSize: string;
  mimeType: string;
  extractedTextFallback?: string;
  userContext?: string;
}): InvestigationRecord {
  const id = generateInvestigationId("VR");
  const nowIso = new Date().toISOString();

  const textBody = input.extractedTextFallback?.trim() || "";
  const wordCount = textBody ? textBody.split(/\s+/).filter(Boolean).length : 0;
  const snippet = textBody
    ? textBody.slice(0, 1400)
    : `Binary PDF uploaded (${input.fileName}, ${input.fileSize}). Server-side PDF OCR/text extraction awaits Python FastAPI (PyMuPDF/Tesseract) or GEMINI_API_KEY.`;

  const docResult: DocumentAnalysisResult = {
    fileName: input.fileName,
    fileSize: input.fileSize,
    pageCountEstimate: Math.max(1, Math.ceil(Math.max(1, wordCount) / 350)),
    mimeType: input.mimeType,
    extractedText: snippet,
    documentMetadata: {
      title: input.fileName.replace(/\.[^.]+$/, ""),
      authorOrOrg: "Pending PDF metadata parser",
      documentDate: new Date().toISOString().slice(0, 10),
      documentType: input.mimeType.includes("pdf") ? "PDF Document" : "Text Document",
      wordCount,
    },
    keyClaims: [
      {
        id: "DOC-1",
        claim: textBody
          ? textBody.split(/(?<=[.!?])\s+/)[0] || input.fileName
          : `Document '${input.fileName}' queued for OCR & claim extraction.`,
        section: "Document Intake",
        verificationNote:
          "Classified as Unverified in mock prototype mode until connected to FastAPI OCR/NLP or GEMINI_API_KEY.",
        status: "Unverified",
      },
    ],
    comparisonFindings: [
      {
        topic: "External Citation Cross-Check",
        documentPosition: input.userContext || "Submitted document assertions",
        externalContext:
          "Live external cross-checking requires FastAPI retrieval or GEMINI_API_KEY.",
        alignment: "Requires Review",
      },
    ],
    overallAssessment: "Parsed by Mock Prototype — Requires Backend Review",
    confidenceRange: {
      low: 40,
      high: 55,
      label: "40%–55% (Mock Prototype)",
    },
    explanation: `Received '${input.fileName}' (${input.fileSize}, ${input.mimeType}). This output is generated by the mock document service adapter so you can inspect the report layout and PDF export flow before attaching your FastAPI OCR/NLP backend.`,
    limitations: [
      "Mock Prototype Layer: Live PDF OCR and external claim verification are not connected.",
      "Configure GEMINI_API_KEY or connect the FastAPI document pipeline for full extraction.",
    ],
  };

  return {
    id,
    type: "document",
    title: docResult.documentMetadata.title,
    submittedSummary: `${input.fileName} (${input.fileSize}) — ${docResult.overallAssessment}`,
    createdAt: nowIso,
    status: "completed",
    assessmentLabel: docResult.overallAssessment,
    assessmentCategory: "neutral",
    confidenceLabel: docResult.confidenceRange.label,
    dataOrigin: "Sample Baseline (Mock)",
    documentResult: docResult,
    evidenceTable: [
      {
        factor: "Document Container",
        observation: `${input.fileName} · ${input.fileSize} · ${input.mimeType}`,
        signal: "Ingested",
        weight: "Metadata",
      },
      {
        factor: "Claim Audit Pipeline",
        observation: "Awaiting FastAPI OCR/NLP or GEMINI_API_KEY",
        signal: "Requires Review",
        weight: "Pending",
      },
    ],
    modelFindings: [
      {
        module: "Mock Document Adapter (FastAPI Placeholder)",
        summary: docResult.explanation,
        uncertainty: "Live OCR and web corroboration not connected",
      },
    ],
    sources: [],
    limitations: docResult.limitations,
  };
}
